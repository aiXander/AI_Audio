"""The world catalogue the promptless-anarchy base corpus is generated from.

A *world* is one musical region: genre tags, instrument pool, mood pool, a tempo range
(None = beatless / free time / rubato), one AudioSparx-style description and a few
production-library keywords. `corpus.py` draws prompts from these in SA3's training-prompt
grammar. The corpus defines the space the fitted distribution can reach, so the catalogue
is built to push every axis to its extremes somewhere, not to be a genre atlas:

- tradition / era / place: club and pop anchors (the DiT renders those best) next to
  early music, ritual, court and regional traditions, avant-garde and sound art
- sound source: acoustic, electronic, found objects, voices as texture, prepared and
  homemade instruments, environmental and electromagnetic recordings
- recording / production: 78 rpm shellac, 1930s field disc, four-track cassette, tape decay,
  bitcrushed toys, binaural, hydrophone, dead room vs cathedral, audiophile hi-fi
- tempo: beatless and rubato, 6-10 BPM up to 300-400 BPM; odd meters (7/8, 11/8, 17/16),
  12/8 polyrhythm, phasing, accelerating forms
- density / dynamics / tonality: one held organ note vs harsh-noise wall; a whispered guqin
  vs crushing doom; drone, modal, atonal, microtonal (just intonation, makam), spectral
- affect: the full range, including dread, grief, hostility and nausea-adjacent unease
- form: loop, five-second sting, ceremony, slow-to-fast form, evolving piece
- surface form of the description itself: terse ("Static. A motionless wall of harsh
  noise.") to long multi-clause prose; technical (Hz, ranks, tunings) to poetic

`family` groups worlds for the analysis. `edge` marks deliberate off-manifold prompts
(impossible hybrids, physical-process and synesthetic descriptions, absurd instrumentation):
keep them separable from the plausible ones. `corpus.py` never renders an edge world in the
pure-tags style, because its edge lives in the description.

Plan and rationale: docs/TODO/sa3-promptless-anarchy.md (AI_Audio repo). Measure a change
with `diversity.py --worlds` before and after.
"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class World:
    id: str
    family: str
    genres: tuple[str, ...]
    instruments: tuple[str, ...]
    moods: tuple[str, ...]
    bpm: tuple[int, int] | None
    desc: str
    keywords: tuple[str, ...] = ()
    track_type: str = "Music"          # "Music" | "Instrument" (stems / solo pieces)


def _split(s: str) -> tuple[str, ...]:
    return tuple(x.strip() for x in s.split(",") if x.strip())


def W(id, family, genres, instruments, moods, bpm, desc, keywords="", track_type="Music"):
    split = _split
    return World(id, family, split(genres), split(instruments), split(moods), bpm, desc,
                 split(keywords), track_type)


